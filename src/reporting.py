"""Reproducible English brief and BI import tables from the canonical SQLite model."""
import argparse
from contextlib import closing
import hashlib
import json
from pathlib import Path

import pandas as pd

from src.data_loader import connect_db, get_dashboard_data, resolve_paths

ROOT = Path(__file__).resolve().parents[1]


def build_star(orders):
    """One row per order; dimensions are unique and all foreign keys are checked."""
    geo_cols = ['country', 'state', 'city']
    geography = orders[geo_cols].drop_duplicates().sort_values(geo_cols).reset_index(drop=True)
    geography.insert(0, 'geography_key', range(1, len(geography) + 1))
    enriched = orders.merge(geography, on=geo_cols, how='left', validate='many_to_one')
    fact_cols = ['orderid', 'orderdate', 'customerid', 'productid', 'geography_key',
                 'sellerid', 'paymentmethod', 'orderstatus', 'quantity', 'unitprice_cents',
                 'merchandise_cents', 'tax_cents', 'shippingcost_cents', 'totalamount_cents',
                 'delivered_revenue_cents']
    fact = enriched[fact_cols].sort_values('orderid').reset_index(drop=True)
    customer = orders[['customerid', 'customername']].drop_duplicates().sort_values('customerid')
    product = orders[['productid', 'productname', 'category', 'brand']].drop_duplicates().sort_values('productid')
    dates = pd.date_range(orders.orderdate.min(), orders.orderdate.max()) if len(orders) else pd.DatetimeIndex([])
    date = pd.DataFrame({'orderdate': dates.strftime('%Y-%m-%d'),
                         'year': dates.year, 'month_number': dates.month,
                         'month': dates.strftime('%Y-%m')})
    tables = {'FactOrders': fact, 'DimCustomer': customer, 'DimProduct': product,
              'DimGeography': geography, 'DimDate': date}
    keys = {'DimCustomer': 'customerid', 'DimProduct': 'productid',
            'DimGeography': 'geography_key', 'DimDate': 'orderdate'}
    if fact.orderid.duplicated().any():
        raise ValueError('FactOrders requires unique orderid; line-item data is unsupported')
    for name, key in keys.items():
        if tables[name][key].isna().any() or tables[name][key].duplicated().any():
            raise ValueError(f'{name} requires a unique non-null {key}')
        if not fact[key].isin(tables[name][key]).all():
            raise ValueError(f'Unmatched {name} foreign key')
    return tables


def money(cents):
    return f'USD {cents / 100:,.2f}' if cents is not None else 'N/A'


def write_report(data, output):
    k = data['kpis']
    category = data['category'].sort_values('delivered_revenue_cents', ascending=False)
    leading = category.iloc[0] if len(category) else None
    returned_share = k['returned_share']
    rate = f'{returned_share:.2%}' if returned_share is not None else 'N/A'
    verified_demo = data['metadata'].get('data_kind') == 'independently generated synthetic demo'
    provenance = ('Independently generated synthetic demonstration. No real Amazon business findings.'
                  if verified_demo else 'User-supplied CSV; source and license unverified. USD is a demo assumption. No real Amazon business findings.')
    limits = ('Product/category and outcome patterns are generated by a seeded demo process. Differences illustrate analysis mechanics; they do not establish market demand or predict a real company’s performance.'
              if verified_demo else 'The source and permission to reuse this user-supplied dataset are unverified. These descriptive results do not establish causal effects or predict a real company’s performance.')
    lines = [
        '# Retail operations — analytical brief', '',
        '> ' + provenance, '',
        '## Decision question', '',
        'How do delivered merchandise sales differ from all-status order bookings, and where should an analyst investigate order outcomes?', '',
        '## Verified descriptive results', '',
        f'- Cohort: {k["total_orders"]:,} unique orders; {k["delivered_orders"]:,} delivered; {k["returned_orders"]:,} returned.',
        f'- Delivered merchandise revenue: **{money(k["delivered_revenue_cents"])}**, net of recorded discount and excluding tax/shipping.',
        f'- All-status booked order value: **{money(k["booked_total_cents"])}**, including tax/shipping. This is not revenue.',
        f'- Delivered merchandise AOV: **{money(k["delivered_aov_cents"])}**. Denominator: delivered unique orders.',
        f'- Returned share of all orders: **{rate}**. This describes the current status of an order-date cohort, not the return-event rate.',
    ]
    if leading is not None:
        share = leading.delivered_revenue_cents / k['delivered_revenue_cents'] if k['delivered_revenue_cents'] else 0
        lines.append(f'- Largest delivered-revenue category: **{leading.category}**, {money(leading.delivered_revenue_cents)} ({share:.1%} of delivered revenue).')
    lines += [
        '', '## Recommended analytical next steps', '',
        '1. Reconcile the delivered-merchandise definition with Finance before adopting it in a real business. It is a portfolio convention, not an accounting recognition policy.',
        '2. Review category order-outcome counts alongside their denominators. Request return reasons, return dates and fulfilment timestamps before attributing causes or proposing an intervention.',
        '3. Obtain acquisition cost, margin, refund amounts and experiment assignments before estimating profit, lifetime value or recoverable revenue. None can be inferred from this dataset.',
        '', '## Limits and reproducibility', '',
        limits,
        'The order snapshot has one product per unique order. Conflicting repeated order IDs are rejected; multi-line orders require an explicit line identifier and a different contract.',
        'All figures are generated from the same SQLite query API as the dashboard. See `reports/metrics.json`, `bi/exports/manifest.json`, `docs/METRICS.md` and `docs/DATA_AUDIT.md`.',
        '',
    ]
    output.write_text('\n'.join(lines), encoding='utf-8')


def export(db_path=None, output_dir=None, report_dir=None):
    output_dir = Path(output_dir or ROOT / 'bi/exports').resolve()
    report_dir = Path(report_dir or ROOT / 'reports').resolve()
    with closing(connect_db(db_path)) as conn:
        data = get_dashboard_data(conn)
    tables = build_star(data['orders'])
    # Check every destination before creating directories or writing any bytes.
    source = Path(data['metadata']['source_path']).resolve()
    protected = {resolve_paths(db_path=db_path)[1].resolve(), source,
                 source.with_suffix(source.suffix + '.metadata.json').resolve()}
    destinations = [output_dir / f'{name}.csv' for name in tables]
    destinations += [output_dir / 'manifest.json', report_dir / 'metrics.json',
                     report_dir / 'business_insights.md']
    for destination in destinations:
        if destination.resolve() in protected:
            raise ValueError(f'Export output would overwrite an input/source/database: {destination}')
    k = data['kpis']
    fact = tables['FactOrders']
    if len(fact) != k['total_orders'] or int(fact.delivered_revenue_cents.sum()) != k['delivered_revenue_cents']:
        raise ValueError('BI fact does not reconcile to the canonical SQL metrics')
    output_dir.mkdir(parents=True, exist_ok=True)
    report_dir.mkdir(parents=True, exist_ok=True)
    files = {}
    for name, table in tables.items():
        path = output_dir / f'{name}.csv'
        table.to_csv(path, index=False, lineterminator='\n')
        files[path.name] = {'rows': len(table), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
    # Avoid embedding machine-specific paths in published artifacts.
    metadata = {k: v for k, v in data['metadata'].items() if k != 'source_path'}
    manifest = {'grain': 'one order with one product per row', 'currency': 'USD (demo assumption)',
                'metadata': metadata, 'files': files, 'expected_metrics': data['kpis']}
    (output_dir / 'manifest.json').write_text(json.dumps(manifest, indent=2, default=str) + '\n')
    (report_dir / 'metrics.json').write_text(json.dumps({'metadata': metadata, 'kpis': k}, indent=2, default=str) + '\n')
    write_report(data, report_dir / 'business_insights.md')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--db', default=None)
    parser.add_argument('--output', default=None)
    parser.add_argument('--reports', default=None)
    args = parser.parse_args()
    manifest = export(args.db, args.output, args.reports)
    print(f'Exported {len(manifest["files"])} validated star-schema tables; fact/SQL reconciliation passed.')


if __name__ == '__main__':
    main()
